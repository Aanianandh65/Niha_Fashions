class Command(BaseCommand):
    help = "Seeds initial products into SQLite database if empty or forced."

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Force re-seeding even if products exist",
        )

    def handle(self, *args, **options):
        force = options.get("force")

        if force:
            Product.objects.all().delete()
            self.stdout.write(self.style.WARNING("Existing products deleted."))

        if Product.objects.count() == 0:
            count = 0
            for item in INITIAL_PRODUCTS:
                Product.objects.create(**item)
                count += 1
            self.stdout.write(
                self.style.SUCCESS(f"Successfully seeded {count} initial products permanently into database.")
            )
        else:
            self.stdout.write(
                self.style.SUCCESS(
                    f"Database already contains {Product.objects.count()} products. Skipping seed."
                )
            )
